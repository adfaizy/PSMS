/**
 * Writes public/psms-config.js (+ .json) so every browser/device gets Cloud ON.
 *
 * Sources (highest wins):
 * 1. process.env (Vercel / CI — required for production)
 * 2. .env.local
 * 3. .env
 *
 * Anon key is safe to expose in the browser (Supabase design).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const publicDir = join(root, 'public')
const outJs = join(publicDir, 'psms-config.js')
const outJson = join(publicDir, 'psms-config.json')

function parseEnvFile(filePath) {
  if (!existsSync(filePath)) return {}
  const out = {}
  for (const line of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const i = t.indexOf('=')
    if (i <= 0) continue
    const key = t.slice(0, i).trim()
    let val = t.slice(i + 1).trim()
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1)
    }
    out[key] = val
  }
  return out
}

const fileEnv = {
  ...parseEnvFile(join(root, '.env')),
  ...parseEnvFile(join(root, '.env.local')),
}

const url = String(
  process.env.VITE_SUPABASE_URL || fileEnv.VITE_SUPABASE_URL || ''
).trim()
const anonKey = String(
  process.env.VITE_SUPABASE_ANON_KEY || fileEnv.VITE_SUPABASE_ANON_KEY || ''
).trim()

mkdirSync(publicDir, { recursive: true })

function readExistingPublicConfig() {
  try {
    if (!existsSync(outJson)) return null
    const json = JSON.parse(readFileSync(outJson, 'utf8'))
    const existingUrl = String(json.url || json.supabaseUrl || '').trim()
    const existingKey = String(json.anonKey || json.supabaseAnonKey || '').trim()
    if (existingUrl && existingKey) return { url: existingUrl, anonKey: existingKey }
  } catch {
    /* ignore */
  }
  return null
}

if (!url || !anonKey) {
  // Keep a committed public/psms-config so Vercel stays Cloud ON without dashboard env vars.
  // (Supabase anon key is meant to be public in the browser.)
  const existing = readExistingPublicConfig()
  if (existing) {
    writeFileSync(outJson, JSON.stringify(existing, null, 2), 'utf8')
    writeFileSync(
      outJs,
      `// Auto-generated by scripts/write-psms-config.mjs — do not edit by hand\n` +
        `// Served to every browser/device that opens this app (including Vercel).\n` +
        `window.__PSMS_CLOUD__ = ${JSON.stringify(existing)};\n`,
      'utf8'
    )
    console.log('[psms-config] Kept existing public/psms-config.js (no env vars; cloud ON worldwide)')
    process.exit(0)
  }

  const stub = `// Auto-generated — no Supabase keys found (env / .env.local)\nwindow.__PSMS_CLOUD__ = null;\n`
  writeFileSync(outJs, stub, 'utf8')
  writeFileSync(outJson, JSON.stringify({ url: '', anonKey: '' }, null, 2), 'utf8')
  const msg =
    '[psms-config] VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY missing — cloud will stay OFF.\n' +
    '  Local: add them to .env.local then run npm run psms-config\n' +
    '  Vercel: commit public/psms-config.js|.json OR set Project → Environment Variables, then Redeploy'
  // On Vercel/CI, fail the build so the live site is never shipped without worldwide cloud
  if (process.env.VERCEL || process.env.CI) {
    console.error(msg)
    process.exit(1)
  }
  console.warn(msg)
  process.exit(0)
}

const payload = { url, anonKey }
writeFileSync(outJson, JSON.stringify(payload, null, 2), 'utf8')
writeFileSync(
  outJs,
  `// Auto-generated by scripts/write-psms-config.mjs — do not edit by hand\n` +
    `// Served to every browser/device that opens this app (including Vercel).\n` +
    `window.__PSMS_CLOUD__ = ${JSON.stringify(payload)};\n`,
  'utf8'
)
const source = process.env.VITE_SUPABASE_URL ? 'process.env' : '.env file'
console.log(`[psms-config] Wrote public/psms-config.js from ${source} (cloud ON worldwide)`)
