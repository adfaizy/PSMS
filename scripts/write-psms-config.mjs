/**
 * Writes public/psms-config.js from .env.local / .env so EVERY browser
 * that loads this app (other PC, phone, another browser) gets the same
 * Supabase cloud settings — not only the machine that has .env.local.
 *
 * Anon key is safe to expose in the browser (Supabase design).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const publicDir = join(root, 'public')
const outJs = join(publicDir, 'psms-config.js')
const outJson = join(publicDir, 'psms-config.json')

function parseEnvFile(filePath) {
  if (!existsSync(filePath)) return {}
  const out = {}
  for (const line of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const i = t.indexOf('=')
    if (i <= 0) continue
    const key = t.slice(0, i).trim()
    let val = t.slice(i + 1).trim()
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1)
    }
    out[key] = val
  }
  return out
}

const env = {
  ...parseEnvFile(join(root, '.env')),
  ...parseEnvFile(join(root, '.env.local')),
}

const url = String(env.VITE_SUPABASE_URL || '').trim()
const anonKey = String(env.VITE_SUPABASE_ANON_KEY || '').trim()

mkdirSync(publicDir, { recursive: true })

if (!url || !anonKey) {
  const stub = `// Auto-generated — no Supabase keys found in .env.local\nwindow.__PSMS_CLOUD__ = null;\n`
  writeFileSync(outJs, stub, 'utf8')
  writeFileSync(outJson, JSON.stringify({ url: '', anonKey: '' }, null, 2), 'utf8')
  console.warn('[psms-config] VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY missing — cloud will stay OFF')
  process.exit(0)
}

const payload = { url, anonKey }
writeFileSync(outJson, JSON.stringify(payload, null, 2), 'utf8')
writeFileSync(
  outJs,
  `// Auto-generated by scripts/write-psms-config.mjs — do not edit by hand\n` +
    `// Served to every browser/device that opens this app.\n` +
    `window.__PSMS_CLOUD__ = ${JSON.stringify(payload)};\n`,
  'utf8'
)
console.log('[psms-config] Wrote public/psms-config.js for all browsers/devices')
